func TestBareAddress(t *testing.T) {
	for in, want := range map[string]string{
		"Priya <Priya@Example.com>":              "priya@example.com",
		"reply+abc@reply.baoopn.com":             "reply+abc@reply.baoopn.com",
		`"Evil" <a@b.example>, <c@d.example>`:    "",
		"not an address":                         "",
		"":                                       "",
		strings.Repeat("a", 2000) + "@x.example": "",
	} {
		if got := BareAddress(in); got != want {
			t.Errorf("BareAddress(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestHeaderTextAndMessageID(t *testing.T) {
	if got := HeaderText("Hall\r\nBcc: x@evil.example \"<b>\"\\   " + strings.Repeat("n", 300)); strings.ContainsAny(got, "\r\n\"<>\\ ") || utf8.RuneCountInString(got) > maxNameRunes {
		t.Fatalf("headerText left something unsafe: %q", got)
	}
	for in, want := range map[string]string{
		"<abc@mail.example>":                 "<abc@mail.example>",
		" abc@mail.example ":                 "<abc@mail.example>",
		"<a@b>\r\nBcc: x@evil.example":       "",
		"<a b@c>":                            "",
		"<a@b><c@d>":                         "",
		"<" + strings.Repeat("a", 300) + ">": "",
		"":                                   "",
	} {
		if got := MessageID(in); got != want {
			t.Errorf("MessageID(%q) = %q, want %q", in, got, want)
		}
	}
}

// Text between a "<" and a later ">" that is not a tag is the writer's.
func TestCleanBodyKeepsAngleBracketsThatAreNotTags(t *testing.T) {
	for in, want := range map[string]string{
		"<p>I love you <3 and 5 > 3</p>":                     "I love you <3 and 5 > 3",
		"<div>a < b and c > d</div>":                         "a < b and c > d",
		"<p>guests <= 120, budget >= $5,000</p>":             "guests <= 120, budget >= $5,000",
		"<P CLASS=x>Hello</P><br/><b>bold</b> <i >it</i >":   "Hello\n\nbold it",
		"<p>one</p><?xml x?><!DOCTYPE y>two<!-- hidden -->":  "one\ntwo",
		"<p>&lt;script&gt;alert(1)&lt;/script&gt;</p>":       "<script>alert(1)</script>",
		"<p>&amp;lt;b&amp;gt; stays encoded once</p>":        "&lt;b&gt; stays encoded once",
		"<scr<script>x</script>ipt>alert(1)</script>fine":    "alert(1)fine",
		"<img src=x onerror=alert(1)>hello<svg/onload=x>":    "hello",
		"<style>p{}</style>text<script>steal()</script> end": "text end",
	} {
		if got, _ := clean("", in, 0); got != want {
			t.Errorf("CleanBody(html %q) = %q, want %q", in, got, want)
		}
	}
}

// Characters nobody can see (zero-width, bidi overrides and isolates) do not reach a
// stored message, a display name or a notice.
func TestInvisibleCharactersAreRemoved(t *testing.T) {
	hidden := string([]rune{0x200b, 0xfeff, 0x202e, 0x2066, 0x2069, 0x200f, 0x061c})
	got, ok := clean("Hel"+hidden+"lo "+string(rune(0x202e))+"dlrow", "", 0)
	if !ok || got != "Hello dlrow" {
		t.Fatalf("body = %q", got)
	}
	if got := HeaderText("North" + hidden + "light " + string(rune(0x202e)) + "Hall"); got != "Northlight Hall" {
		t.Fatalf("headerText = %q", got)
	}
}
