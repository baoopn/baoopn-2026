func TestCleanBodyReducesHTMLToText(t *testing.T) {
	html := `<html><head><title>x</title><style>p { color: red }</style></head><body>
<p>Hello &amp; thank you.</p><script>alert("stolen")</script>
<div>We&#39;d love the 14th&nbsp;&mdash; is it free?</div>
<p>&lt;script&gt;alert(1)&lt;/script&gt; and &amp;lt;b&amp;gt;</p>
<SCRIPT type="text/javascript">never closed`
	got, ok := clean("  \n", html, 0)
	if !ok {
		t.Fatal("an HTML-only email has text")
	}
	want := "Hello & thank you.\n\nWe'd love the 14th — is it free?\n\n<script>alert(1)</script> and &lt;b&gt;"
	if got != want {
		t.Fatalf("got  %q\nwant %q", got, want)
	}
	for _, gone := range []string{"stolen", "color: red", "never closed", "<p>", "<title>"} {
		if strings.Contains(got, gone) {
			t.Fatalf("%q must not survive: %q", gone, got)
		}
	}
}

func TestCleanBodyPrefersTheTextPart(t *testing.T) {
	got, _ := clean("The text part.", "<p>The HTML part.</p>", 0)
	if got != "The text part." {
		t.Fatalf("got %q", got)
	}
}

func TestCleanBodyCapsAndTidies(t *testing.T) {
	got, ok := clean(strings.Repeat("é", 20000), "", 0)
	if !ok || utf8.RuneCountInString(got) != maxInboundRunes {
		t.Fatalf("want %d characters, got %d", maxInboundRunes, utf8.RuneCountInString(got))
	}
	got, _ = clean("a\x00b\x07c\xff\r\n\r\n\r\n\r\nd", "", 0)
	if got != "abc\n\nd" {
		t.Fatalf("control characters, bad bytes and runs of blank lines must go: %q", got)
	}
}

func TestCleanBodyWithNothingLeft(t *testing.T) {
	if got, ok := clean(" \n", "<p> </p>", 2); !ok || got != noText {
		t.Fatalf("an email with attachments and no words is kept as %q, got %q (ok %v)", noText, got, ok)
	}
	if _, ok := clean("", "<p> </p>", 0); ok {
		t.Fatal("an empty email without attachments is nothing to store")
	}
}

